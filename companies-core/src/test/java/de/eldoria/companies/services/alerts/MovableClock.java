package de.eldoria.companies.services.alerts;

import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZoneOffset;

/**
 * A clock in UTC that stands still until it is moved on.
 */
final class MovableClock extends Clock {
    private Instant now = Instant.parse("2026-03-01T12:00:00Z");

    /**
     * @param duration time to move on
     */
    void advance(Duration duration) {
        now = now.plus(duration);
    }

    @Override
    public ZoneId getZone() {
        return ZoneOffset.UTC;
    }

    @Override
    public Clock withZone(ZoneId zone) {
        return this;
    }

    @Override
    public Instant instant() {
        return now;
    }
}
