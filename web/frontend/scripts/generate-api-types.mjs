/**
 * Writes the TypeScript types of the dashboard protocol, `src/api/generated/protocol.ts`, from the protocol's JSON
 * Schema that the `:web-api` module commits (`web/api/src/main/resources/schema/v1/protocol.schema.json`), with
 * json-schema-to-typescript.
 *
 * Every string enum of the schema also becomes a constant of the same name holding its values, so a single import
 * gives the union and its values; the feature names become the constant `Feature`. The `api-types` linter checks that
 * what is committed is what this writes.
 */

import {readFileSync, writeFileSync, mkdirSync} from 'fs'
import {dirname, join} from 'path'
import {compile} from 'json-schema-to-typescript'
import ts from 'typescript'
import {SRC, GREEN, RESET} from './lint-utils.mjs'

export const PROTOCOL_SCHEMA = new URL('../../api/src/main/resources/schema/v1/protocol.schema.json', import.meta.url).pathname
export const PROTOCOL_TARGET = join(SRC, 'api', 'generated', 'protocol.ts')

const LICENSE = `/*
 *     SPDX-License-Identifier: AGPL-3.0-only
 *
 *     Copyright (C) EldoriaRPG Team and Contributor
 */`

/**
 * The protocol types as they should stand for the committed schema.
 */
export async function renderProtocolTypes() {
    const schema = JSON.parse(readFileSync(PROTOCOL_SCHEMA, 'utf-8'))
    const types = await compile({...schema, title: 'ProtocolMessage'}, 'ProtocolMessage', {
        bannerComment: '',
        additionalProperties: false,
        unreachableDefinitions: true,
        format: true,
        style: {singleQuote: true},
    })
    const constants = [enumConstants(schema.$defs ?? {}), featureConstant(schema['x-features'] ?? {})].join('\n')
    const body = `${types}\n${constants}`.replace(/[ \t]+$/gm, '')
    return `${LICENSE}\n${banner()}${ending(body)}`
}

/**
 * The doc comment heading the generated file.
 *
 * @returns the comment
 */
function banner() {
    return `/**
 * Generated by \`node scripts/generate-api-types.mjs\` from the protocol schema of \`:web-api\`. Do not edit: a type
 * changes when the record it describes changes.
 */
`
}

/**
 * The text with exactly one line break at its end.
 *
 * @param text the text
 * @returns the text ending in a line break
 */
function ending(text) {
    return text.endsWith('\n') ? text : `${text}\n`
}

/**
 * A constant for every string enum of the schema.
 *
 * @param schemas the schema's definitions
 * @returns the constants as source
 */
function enumConstants(schemas) {
    return Object.entries(schemas)
        .filter(([, schema]) => Array.isArray(schema.enum) && schema.enum.length > 0 && schema.enum.every(value => typeof value === 'string'))
        .sort(([a], [b]) => compareText(a, b))
        .map(([name, schema]) => renderConstant(name, schema.enum))
        .join('\n')
}

/**
 * The feature names of the schema as a constant and the union of its values.
 *
 * @param features the schema's `x-features`
 * @returns the constant and type as source
 */
function featureConstant(features) {
    const entries = Object.keys(features).sort(compareText).map(name => `    ${JSON.stringify(name)}: ${JSON.stringify(name)},`)
    return `export const Feature = {\n${entries.join('\n')}\n} as const;\n\nexport type Feature = (typeof Feature)[keyof typeof Feature];\n`
}

/**
 * One enum constant.
 *
 * @param name the constant's name
 * @param values the enum's values
 * @returns the constant as source
 */
function renderConstant(name, values) {
    const entries = [...new Set(values)]
        .sort(compareText)
        .map(value => `    ${propertyKey(value)}: ${JSON.stringify(value)},`)
    return `export const ${name} = {\n${entries.join('\n')}\n} as const;\n`
}

/**
 * A value as an object key, quoted where it is no identifier.
 *
 * @param value the value
 * @returns the key as source
 */
function propertyKey(value) {
    return ts.isIdentifierText(value, ts.ScriptTarget.ESNext) ? value : JSON.stringify(value)
}

/**
 * Compares two texts by code unit, so the order does not depend on the machine's locale.
 *
 * @param a one text
 * @param b the other
 * @returns the order
 */
function compareText(a, b) {
    return a < b ? -1 : a > b ? 1 : 0
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
    mkdirSync(dirname(PROTOCOL_TARGET), {recursive: true})
    writeFileSync(PROTOCOL_TARGET, await renderProtocolTypes())
    console.log(`${GREEN}Wrote${RESET} ${PROTOCOL_TARGET.replace(SRC, 'src')}`)
}
